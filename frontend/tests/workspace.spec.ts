import { expect, test } from '@playwright/test';
import { workspaceSchema } from '../src/lib/schemas';
import { money } from '../src/components/subscription-card';

test('upload landing, demo analysis, filters, detail editing and mock SSO', async ({ page }) => {
  const browserErrors: string[] = [];
  page.on('pageerror', (error) => browserErrors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'The subscription clean-up crew.' })).toBeVisible();
  await expect(page.getByRole('banner')).toHaveCount(0);
  await expect(page.getByRole('contentinfo')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight)).toBeTruthy();
  await expect(page.getByRole('button', { name: 'Find my savings' })).toBeDisabled();
  await page.screenshot({ path: 'test-results/welcome-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 667 });
  await page.screenshot({ path: 'test-results/welcome-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight)).toBeTruthy();
  expect(await page.evaluate(() => document.querySelector('.welcome-main')!.scrollHeight <= document.querySelector('.welcome-main')!.clientHeight)).toBeTruthy();
  await page.setViewportSize({ width: 844, height: 390 });
  expect(await page.evaluate(() => document.querySelector('.welcome-main')!.scrollHeight <= document.querySelector('.welcome-main')!.clientHeight)).toBeTruthy();
  await page.setViewportSize({ width: 1440, height: 1100 });
  await expect(page.getByRole('button', { name: 'Explore a demo workspace' })).toHaveCount(0);
  await page.request.post('/api/backend/api/demo');
  await page.reload();
  await expect(page.locator('.subscription-card')).toHaveCount(8);
  await expect(page.getByRole('banner')).toBeVisible();
  await expect(page.getByText('Workspace up to date')).toBeVisible({ timeout: 20000 });
  await expect(page.locator('.savings-stat strong')).toHaveText('£2,820');
  await expect(page.locator('.subscription-card').filter({ hasText: 'Notion' })).toHaveClass(/has-savings/);
  await expect(page.locator('.subscription-card').filter({ hasText: 'Financial Times' })).toHaveClass(/has-suggestion/);
  await expect(page.locator('.sidebar')).toHaveCount(0);
  await page.getByRole('button', { name: 'More filters' }).click();
  await page.getByLabel('Minimum users', { exact: true }).fill('80');
  await page.getByLabel('Maximum users', { exact: true }).fill('100');
  await page.getByLabel('Minimum monthly spend', { exact: true }).fill('1000');
  await page.getByLabel('Minimum monthly savings', { exact: true }).fill('1000');
  await page.getByLabel('Close advanced filters').click();
  await expect(page.locator('.subscription-card')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'View GitHub subscription' })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  const iconTops = await page.locator('.subscription-card').evaluateAll((cards) => {
    const tops: Record<string, number> = {};
    cards.forEach((card) => {
      const name = card.querySelector('h3')?.textContent ?? '';
      tops[name] = card.querySelector('.service-avatar')?.getBoundingClientRect().top ?? -1;
    });
    return tops;
  });
  expect(iconTops.JSTOR).toBe(iconTops['Financial Times']);
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true });
  await page.getByLabel('Search subscriptions').fill('ntion');
  await expect(page.locator('.subscription-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'View Notion subscription' }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Save & analyse' })).toBeDisabled();
  await expect(dialog.getByText('£530', { exact: false }).first()).toBeVisible();
  const state = workspaceSchema.parse(await (await page.request.get('/api/backend/api/workspace')).json());
  const notion = state.services.find((service) => service.name === 'Notion')!;
  const yearly = notion.recommendations.find((item) => item.billing_period === 'annual')!;
  const monthly = notion.recommendations.find((item) => item.billing_period === 'monthly')!;
  await dialog.getByRole('tab', { name: 'Yearly', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Yearly plans' })).toBeVisible();
  await expect(dialog.locator('.recommendation')).toContainText('paid yearly');
  await expect(dialog.locator('.recommendation-amount')).toHaveText(
    `${money(yearly.annual_savings ?? Math.max(0, notion.spend! * 12 - yearly.annual_cost), notion.currency)} / year in potential savings`,
  );
  await dialog.getByRole('tab', { name: 'Monthly', exact: true }).click();
  await expect(dialog.locator('.recommendation-amount')).toHaveText(
    `${money(monthly.monthly_savings, notion.currency)} / month in potential savings`,
  );
  await dialog.getByLabel('Active users').fill('5');
  await dialog.getByRole('button', { name: 'Save & analyse' }).click();
  await expect(dialog.getByText('£900', { exact: false }).first()).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.getByRole('button', { name: 'View Figma subscription' }).click();
  await expect(dialog.getByRole('heading', { name: 'Figma', exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Save & analyse' })).toBeDisabled();
  await page.getByRole('button', { name: 'View Notion subscription' }).click();
  await expect(dialog.getByRole('heading', { name: 'Notion', exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 350));
  await expect.poll(() => dialog.evaluate((node) => Math.round(node.getBoundingClientRect().top))).toBe(0);
  expect(await dialog.evaluate((node) => node.getBoundingClientRect().height)).toBe(1100);
  await page.screenshot({ path: 'test-results/detail-desktop.png', animations: 'disabled' });
  await dialog.getByLabel('Close subscription details').click();
  await expect(dialog).toBeHidden();
  await page.getByLabel('Filter by category').selectOption('Research');
  await expect(page.locator('.subscription-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Get with SSO' }).click();
  await expect(page.getByRole('button', { name: 'Get with SSO' })).toHaveCount(0, { timeout: 15000 });
  await page.getByRole('button', { name: 'View JSTOR subscription' }).click();
  await expect(dialog.locator('.source-tag').first()).toHaveText('SSO');
  await dialog.getByLabel('Close subscription details').click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.getByRole('button', { name: 'Fill gaps & analyse' }).click();
  await expect(page.locator('.sso-card-button')).toHaveCount(0, { timeout: 15000 });
  await expect(page.getByRole('button', { name: 'Fill gaps & analyse' })).toBeEnabled();
  await page.getByRole('button', { name: 'Fill gaps & analyse' }).click();
  await expect(dialog.getByRole('heading', { name: 'Reanalyse everything?' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Keep current analysis' }).click();
  await page.reload();
  await expect(page.locator('.subscription-card')).toHaveCount(8);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/workspace-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.getByRole('button', { name: 'Add subscriptions' }).click();
  await page.getByLabel('Upload subscription spreadsheets').setInputFiles({
    name: 'new-services.csv', mimeType: 'text/csv', buffer: Buffer.from('Service,Users,Monthly spend\nLinear,5,100'),
  });
  await page.getByRole('button', { name: 'Find my savings' }).click();
  await expect(page.locator('.subscription-card')).toHaveCount(9);
  await page.getByRole('button', { name: 'View Linear subscription' }).click();
  await expect(dialog.getByText('Add GEMINI_API_KEY', { exact: false })).toBeVisible({ timeout: 15000 });
  await dialog.getByLabel('Close subscription details').click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Ask AI to filter' }).click();
  await page.getByLabel('Natural language filter request').fill('Show design tools with savings');
  await page.getByRole('button', { name: 'Apply filter' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'GEMINI_API_KEY' })).toBeVisible();
  await page.getByLabel('Close AI filter').click();
  await page.getByLabel('Switch workspace').click();
  await page.getByRole('button', { name: 'New workspace', exact: true }).click();
  await page.getByLabel('Workspace name').fill('Research team');
  await page.getByRole('button', { name: 'Create workspace' }).click();
  await expect(page.getByRole('heading', { name: 'The subscription clean-up crew.' })).toBeVisible();
  await page.getByLabel('Switch workspace').click();
  await page.getByRole('button', { name: 'My workspace', exact: true }).click();
  await expect(page.locator('.subscription-card')).toHaveCount(9);
  await page.getByLabel('Switch workspace').click();
  await page.getByRole('button', { name: 'Delete workspace', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete workspace', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'The subscription clean-up crew.' })).toBeVisible();
  await expect(page.getByRole('banner')).toHaveCount(0);
  expect(browserErrors).toEqual([]);
});
